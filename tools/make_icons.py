"""
Dev-time helper: renders colourful emoji icons (Windows "Segoe UI Emoji") into seo_icons.py as
base64 PNGs, so the app can show full-colour icons without Pillow at run time.

    python tools/make_icons.py
"""
import base64
import io
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONT = r"C:\Windows\Fonts\seguiemj.ttf"
SIZES = (20, 26)
ICONS = {
    "folder": "\U0001F4C1", "gear": "\u2699\ufe0f", "search": "\U0001F50D", "page": "\U0001F4C4",
    "bolt": "\u26A1", "progress": "\u23F3", "globe": "\U0001F310", "pencil": "\u270F\ufe0f",
    "image": "\U0001F5BC\ufe0f", "office": "\U0001F3E2", "tools": "\U0001F6E0\ufe0f", "shield": "\U0001F6E1\ufe0f",
    "skip": "\u23ED\ufe0f", "key": "\U0001F511", "robot": "\U0001F916", "money": "\U0001F4B0",
    "save": "\U0001F4BE", "play": "\u25B6\ufe0f", "stop": "\u23F9\ufe0f", "chart": "\U0001F4CA",
    "retry": "\U0001F504", "trash": "\U0001F5D1\ufe0f", "restore": "\u267B\ufe0f", "files": "\U0001F5C2\ufe0f",
    "check": "\u2705", "warn": "\u26A0\ufe0f", "cross": "\u274C", "link": "\U0001F517", "open": "\U0001F4C2",
    "copy": "\U0001F4CB", "rocket": "\U0001F680",
}


def render(ch: str, size: int) -> bytes:
    font = ImageFont.truetype(FONT, 109)
    im = Image.new("RGBA", (200, 200), (0, 0, 0, 0))
    ImageDraw.Draw(im).text((20, 20), ch, font=font, embedded_color=True)
    im = im.crop(im.getbbox()).resize((size, size), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=True)
    return buf.getvalue()


def main():
    out = ['"""Generated by tools/make_icons.py — colourful icons as base64 PNG (small, large)."""', "", "ICONS = {"]
    for name, ch in ICONS.items():
        parts = [base64.b64encode(render(ch, s)).decode() for s in SIZES]
        out.append(f'    "{name}": (\n        "{parts[0]}",\n        "{parts[1]}"),')
    out.append("}")
    Path(__file__).resolve().parent.parent.joinpath("seo_icons.py").write_text("\n".join(out) + "\n", encoding="utf-8")
    # contact sheet for a quick visual check
    sheet = Image.new("RGBA", (len(ICONS) * 34, 40), (255, 255, 255, 255))
    for i, ch in enumerate(ICONS.values()):
        sheet.paste(Image.open(io.BytesIO(render(ch, 26))), (i * 34 + 4, 7))
    sheet.save(Path(__file__).resolve().parent / "icon_sheet.png")
    print("wrote seo_icons.py with", len(ICONS), "icons")


if __name__ == "__main__":
    main()
